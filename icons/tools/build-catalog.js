/* Build js/icons-data.js from everything in sets/.
   Run from the icons/ folder:  node tools/build-catalog.js

   Each set is a folder of plain .svg files plus the licence they came with.
   A set is described once, in SETS below, because a folder of files cannot say
   where it came from or what it is licensed under — and both have to travel
   with the icons.

   The catalogue inlines each icon's markup rather than pointing at its file:
   the studio recolours and resizes what it draws, and 340 fetches to show one
   grid is a page that never settles. The files stay on disk as the source of
   truth and the thing you copy into a project. */
const fs = require('fs');
const path = require('path');

const SETS = [
  {
    id: 'dashicons',
    name: 'Dashicons',
    by: 'WordPress',
    source: 'https://github.com/WordPress/dashicons',
    mirror: 'https://www.svgrepo.com/collection/dashicons-filled-interface-icons/',
    licence: 'GPL-2.0-or-later',
    note: 'The official WordPress icon set. Solid shapes on a 20x20 grid.',
  },
];

// Filename prefixes are the set's own grouping — admin-, editor-, media- and so
// on — so the tags cost nothing to derive and mean what the author meant.
const PREFIX_TAGS = ['admin', 'editor', 'buddicons', 'welcome', 'media', 'format', 'controls',
                     'table', 'image', 'database', 'chart', 'align', 'arrow', 'menu', 'embed',
                     'playlist', 'video', 'star', 'plus', 'cloud', 'twitter', 'facebook'];
// A handful of words worth finding by, where the filename does not start with them.
const WORD_TAGS = {
  social: ['facebook', 'twitter', 'instagram', 'linkedin', 'pinterest', 'reddit', 'youtube', 'whatsapp',
           'spotify', 'twitch', 'google', 'googleplus', 'amazon', 'xing', 'podio', 'share', 'rss'],
  arrows: ['arrow', 'sort', 'leftright', 'randomize', 'migrate', 'move', 'undo', 'redo', 'update', 'redo'],
  text:   ['editor', 'heading', 'text', 'paragraph', 'html', 'shortcode', 'translation'],
  files:  ['media', 'pdf', 'download', 'upload', 'open-folder', 'archive', 'clipboard', 'index-card'],
  ui:     ['menu', 'dismiss', 'no', 'yes', 'plus', 'minus', 'ellipsis', 'search', 'filter', 'lock',
           'unlock', 'hidden', 'visibility', 'info', 'warning', 'star', 'heart', 'flag', 'bell'],
};

const tagsFor = (name) => {
  const out = new Set();
  const head = name.split('-')[0];
  if (PREFIX_TAGS.includes(head)) out.add(head);
  for (const [tag, words] of Object.entries(WORD_TAGS))
    if (words.some(w => name === w || name.startsWith(w + '-'))) out.add(tag);
  if (!out.size) out.add('misc');
  return [...out];
};

const icons = [];
const sets = [];

for (const set of SETS) {
  const dir = path.join('sets', set.id);
  const files = fs.readdirSync(dir).filter(f => f.endsWith('.svg')).sort();
  for (const file of files) {
    const svg = fs.readFileSync(path.join(dir, file), 'utf8');
    const open = svg.match(/<svg[^>]*>/);
    if (!open) { console.warn('no <svg> in', file); continue; }
    const vb = (open[0].match(/viewBox="([^"]+)"/) || [, '0 0 24 24'])[1];
    let body = svg.slice(open.index + open[0].length).replace(/<\/svg>\s*$/, '').trim();
    // The sizing rect every Dashicon opens with draws nothing and only gets in
    // the way of a bounding box.
    body = body.replace(/<rect[^>]*fill="none"[^>]*\/>/g, '').trim();
    body = body.replace(/\s+/g, ' ');
    icons.push({ s: set.id, n: file.replace(/\.svg$/, ''), vb, d: body });
  }
  sets.push({ ...set, count: files.length });
}

for (const icon of icons) icon.t = tagsFor(icon.n);

const out =
`/* Generated by tools/build-catalog.js — do not edit by hand.
   ${sets.map(s => `${s.name}: ${s.count} icons, ${s.licence}, ${s.source}`).join('\n   ')}

   Each icon is { s: set, n: name, vb: viewBox, d: markup, t: tags }. The markup
   is the file's contents minus the <svg> wrapper, so the studio can draw it at
   any size in any colour. */
window.ICON_SETS = ${JSON.stringify(sets, null, 2)};
window.ICONS = [
${icons.map(i => '  ' + JSON.stringify(i)).join(',\n')}
];
`;
fs.mkdirSync('js', { recursive: true });
fs.writeFileSync(path.join('js', 'icons-data.js'), out);
console.log(`${icons.length} icons from ${sets.length} set(s) -> js/icons-data.js (${Math.round(out.length / 1024)}KB)`);
console.log('tags:', [...new Set(icons.flatMap(i => i.t))].sort().join(' '));
